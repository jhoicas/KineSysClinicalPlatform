const LOCAL_STORAGE_KEY = 'corebody_exercise_library_v1';

export const loadExerciseLibrary = (): LibraryExercise[] => {
  try {
    const saved = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.error('Error loading exercise library from localStorage:', err);
  }
  return INITIAL_EXERCISE_LIBRARY;
};

export const saveExerciseLibrary = (exercises: LibraryExercise[]): void => {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(exercises));
  } catch (err) {
    console.error('Error saving exercise library to localStorage:', err);
  }
};
